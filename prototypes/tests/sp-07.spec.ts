import { expect, test } from "@playwright/test";

test("SP-07 keyboard-only connection, resize, cancellation, native undo and deletion use the correct focus scope", async ({ page }) => {
  await page.goto("/?sp=sp-07");
  const canvas = page.getByRole("region", { name: "Diagram canvas" });
  const status = page.getByRole("status");
  const connect = page.getByRole("button", { name: "Connect to…" });
  const resize = page.getByRole("button", { name: "Resize service…" });
  const draft = page.getByRole("textbox", { name: "Label draft" });
  const read = () => page.getByTestId("graph").textContent().then((value) => JSON.parse(value!));
  const press = (key: string) => page.keyboard.press(key);
  await expect(canvas).toBeVisible();
  await press("Tab");
  await expect(canvas).toBeFocused();
  await expect(canvas).toHaveCSS("outline-style", "solid");
  await expect(canvas).toHaveCSS("outline-width", "3px");
  await press("Enter");
  await expect(status).toHaveText("Service selected");
  await press("Tab");
  await expect(connect).toBeFocused();
  await press("Enter");
  const modal = page.getByRole("dialog", { name: "Connect service" });
  await expect(modal.getByRole("combobox", { name: "Target" })).toBeFocused();
  await press("Delete");
  expect(await read()).toMatchObject({ service: true, edge: null, selected: true, history: 0 });
  await press("Escape");
  await expect(modal).toHaveCount(0);
  await expect(connect).toBeFocused();
  await expect(status).toHaveText("Command cancelled");
  await press("Enter");
  await press("ArrowDown");
  await press("Tab");
  await expect(modal.getByRole("button", { name: "Apply" })).toBeFocused();
  await press("Enter");
  await expect(status).toHaveText("Connection committed");
  expect(await read()).toMatchObject({ edge: "database", history: 1 });
  await expect(connect).toBeFocused();
  await press("Tab");
  await expect(resize).toBeFocused();
  await press("Enter");
  const width = page.getByRole("spinbutton", { name: "Width" });
  await expect(width).toBeFocused();
  await press("Control+a");
  await page.keyboard.type("180");
  await press("Tab");
  await press("Enter");
  await expect(status).toHaveText("Resize committed");
  expect(await read()).toMatchObject({ width: 180, history: 2 });
  await expect(resize).toBeFocused();
  await press("Tab");
  await expect(draft).toBeFocused();
  await press("End");
  await page.keyboard.type(" edited");
  await expect(draft).toHaveValue("Service edited");
  await press("Control+z");
  await expect(draft).toHaveValue("Service");
  await press("Delete");
  expect(await read()).toMatchObject({ service: true, width: 180, history: 2 });
  await press("Shift+Tab");
  await press("Shift+Tab");
  await press("Shift+Tab");
  await expect(canvas).toBeFocused();
  await press("Delete");
  expect(await read()).toMatchObject({ service: false, edge: null, history: 3 });
  await press("Control+z");
  expect(await read()).toMatchObject({ service: true, edge: "database", width: 180, history: 2 });
  await press("Escape");
  await expect(status).toHaveText("Selection cleared");
});
