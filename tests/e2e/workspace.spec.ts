test("T-03-04 marquee requires full containment, supports Shift union, and Escape cancels an active gesture", async ({ page }) => {
  await openSample(page);
  const client = (await node(page, "Client").boundingBox())!;
  const start = { x: client.x - 10, y: client.y - 10 };
  async function dragTo(right: number, cancel = false) {
    await page.mouse.move(start.x, start.y);
    await page.mouse.down();
    await page.mouse.move(right, client.y + client.height + 10, { steps: 4 });
    await expect(page.locator(".canvas-marquee")).toBeVisible();
    if (cancel) await page.keyboard.press("Escape");
    await page.mouse.up();
  }
  await dragTo(client.x + client.width / 2);
  await expect(page.locator(".diagram-node[data-selected='true']")).toHaveCount(0);
  await clickNode(page, "Gateway");
  await dragTo(client.x + client.width + 10, true);
  await expect(node(page, "Gateway")).toHaveAttribute("data-selected", "true");
  await page.keyboard.down("Shift");
  await dragTo(client.x + client.width + 10);
  await page.keyboard.up("Shift");
  await expect(node(page, "Client")).toHaveAttribute("data-selected", "true");
  await expect(node(page, "Gateway")).toHaveAttribute("data-selected", "true");
  await expect(page.locator(".react-flow__edge [data-selected='true']")).toHaveCount(0);
  await expect(status(page)).toContainText("2 selected");
});

test("T-03-05 scopes keyboard selection and keeps responsive drawers accessible", async ({ page }, info) => {
  await openSample(page);
  const left = page.getByRole("button", { name: "Component library", exact: true });
  const right = page.getByRole("button", { name: "Properties", exact: true });
  const components = page.getByRole("complementary", { name: "Component library" });
  const properties = page.getByRole("complementary", { name: "Properties" });
  await expect(components).toBeVisible();
  await expect(properties).toBeVisible();
  await canvas(page).focus();
  await page.keyboard.press("Control+a");
  await expect(status(page)).toContainText("13 selected");
  await page.keyboard.press("Escape");
  await expect(status(page)).toContainText("Hold Space to pan");
  const help = page.getByRole("button", { name: "Keyboard shortcuts" });
  await help.click();
  await expect(page.getByRole("dialog", { name: "Keyboard shortcuts" })).toBeVisible();
  await page.keyboard.press("Control+a");
  await expect(status(page)).toContainText("Hold Space to pan");
  await page.keyboard.press("Escape");
  await expect(help).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(left).toBeFocused();
  await page.keyboard.press("Enter");
  await expect(components).toHaveCount(0);
  await page.keyboard.press("Enter");
  await expect(components).toBeVisible();
  await properties.getByRole("button", { name: "Select all", exact: true }).click();
  await expect(status(page)).toContainText("13 selected");
  await properties.getByRole("button", { name: "Clear selection", exact: true }).click();
  await page.setViewportSize({ width: 1280, height: 720 });
  await expect(components).toHaveCSS("width", "224px");
  await expect(properties).toHaveCSS("width", "280px");
  await page.setViewportSize({ width: 1100, height: 720 });
  await expect(components).toHaveCSS("width", "200px");
  await expect(properties).toHaveCSS("width", "256px");
  await page.setViewportSize({ width: 940, height: 730 });
  await expect(components).toHaveCount(0);
  await expect(properties).toHaveCount(0);
  const canvasBefore = (await canvas(page).boundingBox())!.width;
  await left.click();
  await expect(components.getByRole("heading", { name: "Component library", exact: true })).toBeFocused();
  await right.click();
  await expect(components).toHaveCount(0);
  await expect(properties.getByRole("heading", { name: "Properties" })).toBeFocused();
  await expect(properties.getByLabel("Find an object")).toBeVisible();
  expect((await canvas(page).boundingBox())!.width).toBe(canvasBefore);
  await properties.getByLabel("Find an object").selectOption({ label: "Sample service" });
  if (info.project.name === "chrome") {
    await page.evaluate(() => window.getSelection()?.removeAllRanges());
    await page.screenshot({ path: info.outputPath("compact.png") });
  }
  await page.keyboard.press("Escape");
  await expect(properties).toHaveCount(0);
  await expect(right).toBeFocused();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(940);
});
