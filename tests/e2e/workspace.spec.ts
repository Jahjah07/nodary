import { expect, test, type Page } from "@playwright/test";

test.use({ viewport: { width: 1440, height: 900 } });

const example = "/editor/?id=00000000-0000-4000-8000-000000000001";
const canvas = (page: Page) => page.getByRole("region", { name: "Diagram canvas" });
const node = (page: Page, label: string) => page.locator(".diagram-node").filter({ hasText: label });
const matrix = (page: Page) => page.locator(".react-flow__viewport").evaluate((element) => {
  const css = new DOMMatrixReadOnly(getComputedStyle(element).transform);
  return { x: css.e, y: css.f, zoom: css.a };
});
const status = (page: Page) => page.locator(".editor-status");
async function openSample(page: Page) {
  expect((await page.goto(example))?.status()).toBe(200);
  await expect(node(page, "Sample service")).toBeVisible();
  await expect(page.getByRole("heading", { name: "Service architecture" })).toBeVisible();
  await expect.poll(async () => (await matrix(page)).zoom).toBeLessThan(1);
}
async function clickNode(page: Page, label: string, button: "left" | "right" = "left") {
  const box = (await node(page, label).boundingBox())!;
  await page.mouse.click(box.x + box.width / 2, box.y + box.height / 2, { button });
}

test("T-03-01 creates a temporary blank diagram and preserves work across static library navigation", async ({ page, baseURL }, info) => {
  const failures: string[] = [];
  page.on("pageerror", (error) => failures.push(error.message));
  page.on("request", (request) => { if (new URL(request.url()).origin !== baseURL) failures.push(request.url()); });
  page.on("response", (response) => { if (response.status() >= 400) failures.push(`${response.status()} ${response.url()}`); });
  await page.goto("/");
  await expect(page.getByText("No diagrams yet")).toBeVisible();
  const create = page.getByRole("button", { name: "New diagram" });
  await create.click();
  const dialog = page.getByRole("dialog", { name: "New diagram" });
  await dialog.getByRole("button", { name: "Cancel" }).click();
  await expect(create).toBeFocused();
  await expect(page.getByText("No diagrams yet")).toBeVisible();
  await create.click();
  const input = dialog.getByRole("textbox", { name: "Diagram name" });
  await input.fill("Bad\uFFFF title");
  await dialog.getByRole("button", { name: "Create diagram" }).click();
  await expect(dialog.getByRole("alert")).toContainText("U+FFFF");
  await input.press("Control+a");
  await expect.poll(async () => input.evaluate((el: HTMLInputElement) => el.selectionEnd)).toBe("Bad\uFFFF title".length);
  await input.fill("Event processing");
  await dialog.getByLabel("Category").selectOption("architecture");
  await dialog.getByRole("button", { name: "Create diagram" }).click();
  await expect(page.getByRole("heading", { name: "Event processing" })).toBeFocused();
  const opened = page.url();
  expect(opened).toMatch(/\/editor\/\?id=[0-9a-f-]{36}$/);
  await expect(page.getByText("Temporary session")).toBeVisible();
  await expect(page.getByText("Blank canvas")).toBeVisible();
  await page.getByRole("button", { name: "Snap", exact: true }).click();
  await expect(page.getByRole("button", { name: "Snap", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.getByRole("link", { name: "Back to diagram library" }).click();
  await expect(page.getByRole("link", { name: "Event processing" })).toBeVisible();
  if (info.project.name === "chrome") await page.screenshot({ path: info.outputPath("library.png") });
  await page.goBack({ waitUntil: "commit" });
  await expect(page).toHaveURL(opened);
  await expect(page.getByRole("button", { name: "Snap", exact: true })).toHaveAttribute("aria-pressed", "true");
  await page.goForward({ waitUntil: "commit" });
  await page.getByRole("link", { name: "Event processing" }).click();
  await expect(page.getByRole("heading", { name: "Event processing" })).toBeVisible();
  let warned = false;
  page.once("dialog", async (warning) => { warned = warning.type() === "beforeunload"; await warning.accept(); });
  await page.reload();
  await expect(page.getByRole("status")).toHaveText("Diagram not found.");
  expect(warned).toBe(true);
  expect(failures).toEqual([]);
});

test("T-03-02/03 controls projection, clamped zoom, pointer anchoring and independent grid/snap", async ({ page }) => {
  await openSample(page);
  const surface = (await canvas(page).boundingBox())!;
  const initial = await matrix(page);
  const rendered = node(page, "Sample service");
  const box = (await rendered.boundingBox())!;
  expect(box.x - surface.x).toBeCloseTo(initial.x + 279 * initial.zoom, 0);
  expect(box.y - surface.y).toBeCloseTo(initial.y + 124 * initial.zoom, 0);
  await expect(rendered).toHaveAttribute("data-component", "arch.application");
  await expect(page.locator(".react-flow__node[data-id='00000000-0000-4000-8000-00000000000c']")).toHaveCount(1);
  await expect(page.locator(".react-flow__edge")).toHaveCount(5);
  await canvas(page).focus();
  const pivot = { x: surface.width / 2 + 125, y: surface.height / 2 - 110 };
  await page.mouse.move(surface.x + pivot.x, surface.y + pivot.y);
  await page.keyboard.down("Control");
  await page.mouse.wheel(0, -180);
  await page.keyboard.up("Control");
  await expect.poll(async () => (await matrix(page)).zoom).toBeGreaterThan(initial.zoom);
  const after = await matrix(page);
  for (const axis of ["x", "y"] as const) {
    expect(Math.abs((pivot[axis] - after[axis]) / after.zoom - (pivot[axis] - initial[axis]) / initial.zoom)).toBeLessThan(.05);
  }
  const plus = page.getByRole("button", { name: "Zoom in", exact: true });
  const minus = page.getByRole("button", { name: "Zoom out", exact: true });
  for (let i = 0; i < 24 && await plus.isEnabled(); i++) await plus.click();
  await expect(page.getByLabel("Zoom level")).toHaveText("200%");
  await expect(plus).toBeDisabled();
  for (let i = 0; i < 24 && await minus.isEnabled(); i++) await minus.click();
  await expect(page.getByLabel("Zoom level")).toHaveText("25%");
  await expect(minus).toBeDisabled();
  await page.getByRole("button", { name: "Reset zoom" }).click();
  await expect(page.getByLabel("Zoom level")).toHaveText("100%");
  await page.getByRole("button", { name: "Fit diagram" }).click();
  await expect.poll(async () => (await matrix(page)).zoom).toBeCloseTo(initial.zoom, 4);
  const grid = page.getByRole("button", { name: "Grid", exact: true });
  const snap = page.getByRole("button", { name: "Snap", exact: true });
  await grid.click();
  await expect(page.locator(".canvas-grid")).toHaveCount(0);
  await expect(snap).toHaveAttribute("aria-pressed", "false");
  await snap.click();
  await expect(snap).toHaveAttribute("aria-pressed", "true");
  await expect(grid).toHaveAttribute("aria-pressed", "false");
  await grid.click();
  await expect(page.locator(".canvas-grid")).toHaveCount(1);
  await expect(snap).toHaveAttribute("aria-pressed", "true");
  await clickNode(page, "Sample service");
  await expect(page.getByText("34, 60", { exact: true })).toBeVisible();
});

test("T-03-03 pans with Space, the middle button, and regular wheel without graph selection", async ({ page }) => {
  await openSample(page);
  const frame = (await canvas(page).boundingBox())!;
  const position = { x: frame.x + frame.width * .55, y: frame.y + frame.height * .65 };
  await canvas(page).focus();
  const initial = await matrix(page);
  await page.keyboard.down("Space");
  await page.mouse.move(position.x, position.y);
  await page.mouse.down();
  await page.mouse.move(position.x + 45, position.y + 25);
  await page.keyboard.up("Space");
  await page.mouse.move(position.x + 60, position.y + 40);
  await page.mouse.up();
  await expect.poll(async () => (await matrix(page)).x).toBeCloseTo(initial.x + 60, 3);
  await expect.poll(async () => (await matrix(page)).y).toBeCloseTo(initial.y + 40, 3);
  await expect(canvas(page)).toHaveAttribute("data-tool", "select");
  await page.mouse.down({ button: "middle" });
  await page.mouse.move(position.x + 30, position.y + 65);
  await page.mouse.up({ button: "middle" });
  await expect.poll(async () => (await matrix(page)).x).toBeCloseTo(initial.x + 30, 3);
  const beforeWheel = await matrix(page);
  await page.mouse.wheel(0, 76);
  await expect.poll(async () => (await matrix(page)).y).toBeCloseTo(beforeWheel.y - 76, 3);
  await page.getByRole("button", { name: "Pan", exact: true }).click();
  const beforePan = await matrix(page);
  await page.mouse.move(position.x, position.y);
  await page.mouse.down();
  await page.mouse.move(position.x + 22, position.y);
  await page.mouse.up();
  await expect.poll(async () => (await matrix(page)).x).toBeCloseTo(beforePan.x + 22, 3);
  await expect(status(page)).toContainText("Hold Space to pan");
  await expect(page.locator(".diagram-node[data-selected='true']")).toHaveCount(0);
});

